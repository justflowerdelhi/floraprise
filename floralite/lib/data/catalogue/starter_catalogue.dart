import '../repositories/product_repository.dart';

class StarterCatalogueProduct {
  final String name;
  final String category;
  final String defaultUnit;
  final int sellingPricePaise;
  final int? purchasePricePaise;
  final int gstPercent;
  final String manufacturerBarcode;
  final bool trackInventory;
  final int minStock;
  final String supplier;

  const StarterCatalogueProduct({
    required this.name,
    required this.category,
    required this.defaultUnit,
    required this.sellingPricePaise,
    this.purchasePricePaise,
    this.gstPercent = 12,
    this.manufacturerBarcode = '',
    this.trackInventory = true,
    this.minStock = 5,
    this.supplier = '',
  });

  ProductUpsertInput toProductInput() {
    return ProductUpsertInput(
      name: name,
      category: category,
      defaultUnit: defaultUnit,
      sellingPricePaise: sellingPricePaise,
      purchasePricePaise: purchasePricePaise,
      gstPercent: gstPercent,
      manufacturerBarcode: manufacturerBarcode,
      florapriseBarcode: '',
      trackInventory: trackInventory,
      minStock: minStock,
      supplier: supplier,
      active: true,
      favorite: false,
    );
  }
}

